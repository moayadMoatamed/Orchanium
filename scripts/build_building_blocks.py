"""Resolve building_blocks_names.txt via PubChem into building_blocks.yaml.
Names that fail to resolve are reported and left out."""
from __future__ import annotations

import asyncio
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from orchanium.chem import pubchem  # noqa: E402

DATA = Path(__file__).resolve().parents[1] / "backend" / "orchanium" / "chem" / "data"


async def main():
    names = [ln.strip() for ln in (DATA / "building_blocks_names.txt").read_text(encoding="utf-8").splitlines()
             if ln.strip() and not ln.startswith("#")]
    res = await pubchem.resolve_many(names)
    entries, failed = {}, []
    for name in names:
        r = res[name]
        if not r.ok:
            failed.append(name)
            continue
        entries.setdefault(r.inchikey, {"name": name, "smiles": r.smiles, "cid": r.cid})
    (DATA / "building_blocks.yaml").write_text(
        "# Generated by scripts/build_building_blocks.py from PubChem. Approximation of purchasability.\n"
        + yaml.safe_dump(entries, sort_keys=True, allow_unicode=True), encoding="utf-8")
    print(f"resolved {len(entries)} unique / {len(names)} names; failed: {failed}")


if __name__ == "__main__":
    asyncio.run(main())
